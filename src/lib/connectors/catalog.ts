const BY_ID = new Map(CONNECTOR_CATALOG.map((m) => [m.id, m]));

export function getConnector(id: string): ConnectorManifest | undefined {
  return BY_ID.get(id);
}

export function connectorsProviding(action: string): ConnectorManifest[] {
  return CONNECTOR_CATALOG.filter((m) => (m.actions as string[]).includes(action));
}
